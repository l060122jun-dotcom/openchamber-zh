/**
 * Strings the Chinese fork adds on top of upstream: they replace copy that was
 * still hardcoded English at the call site (command rename toast, TTS preview
 * failures, MCP JSON import errors, port forward labels).
 *
 * The two Chinese dictionaries carry these keys themselves with real Chinese
 * copy; this module is what every other locale answers with. English is the base
 * because the app already falls back to it, so an untranslated locale shows the
 * English sentence rather than a missing key.
 */

/** The locales that answer the fork keys from here; the Chinese dictionaries carry their own copy. */
type ForkLocale = 'en' | 'de' | 'fr' | 'nl' | 'es' | 'pt-BR' | 'uk' | 'ko' | 'pl' | 'ja' | 'tr' | 'ar' | 'he';

type Values = readonly [
  /* commandRenamed */ string,
  /* previewFailed */ string,
  /* mcpEmpty */ string,
  /* mcpInvalid */ string,
  /* mcpObjectRequired */ string,
  /* mcpEmptyServers */ string,
  /* mcpMultipleServers */ string,
  /* mcpInvalidEntry */ string,
  /* mcpUnrecognized */ string,
  /* fwdLocalTarget */ string,
  /* fwdLocalListen */ string,
  /* fwdRemoteListen */ string,
  /* fwdRemoteTarget */ string,
  /* fwdLocalTargetHint */ string,
  /* fwdLocalListenHint */ string,
  /* fwdRemoteListenHint */ string,
  /* fwdRemoteTargetHint */ string,
];

function messages(values: Values) {
  return {
    'settings.commands.sidebar.toast.commandRenamed': values[0],
    'settings.voice.page.preview.failed': values[1],
    'settings.mcp.import.empty': values[2],
    'settings.mcp.import.invalid': values[3],
    'settings.mcp.import.objectRequired': values[4],
    'settings.mcp.import.emptyServers': values[5],
    'settings.mcp.import.multipleServers': values[6],
    'settings.mcp.import.invalidEntry': values[7],
    'settings.mcp.import.unrecognized': values[8],
    'settings.remoteInstances.page.forward.localTarget': values[9],
    'settings.remoteInstances.page.forward.localListen': values[10],
    'settings.remoteInstances.page.forward.remoteListen': values[11],
    'settings.remoteInstances.page.forward.remoteTarget': values[12],
    'settings.remoteInstances.page.forward.localTargetHint': values[13],
    'settings.remoteInstances.page.forward.localListenHint': values[14],
    'settings.remoteInstances.page.forward.remoteListenHint': values[15],
    'settings.remoteInstances.page.forward.remoteTargetHint': values[16],
  };
}

